export type OutputFormat = 'image/jpeg' | 'image/webp' | 'image/png'

export interface ProcessOptions {
  format: OutputFormat
  quality: number
  maxWidth?: number
  maxHeight?: number
  targetKB?: number
}

export interface ProcessResult {
  blob: Blob
  width: number
  height: number
  qualityUsed: number
  reachedTarget: boolean
}

function canvasToBlob(canvas: HTMLCanvasElement, type: OutputFormat, quality: number): Promise<Blob> {
  return new Promise((resolve, reject) => {
    canvas.toBlob(blob => blob ? resolve(blob) : reject(new Error('This image format could not be generated by your browser.')), type, quality)
  })
}

export async function processImage(file: File, options: ProcessOptions): Promise<ProcessResult> {
  if (!file.type.startsWith('image/')) throw new Error('Please select an image file.')
  const allowed = ['image/jpeg', 'image/png', 'image/webp']
  if (!allowed.includes(file.type)) throw new Error('Supported input formats: JPG, PNG and WebP.')
  if (file.size > 25 * 1024 * 1024) throw new Error('Each image must be 25 MB or smaller.')

  const bitmap = await createImageBitmap(file, { imageOrientation: 'from-image' })
  try {
    const scale = Math.min(
      1,
      options.maxWidth ? options.maxWidth / bitmap.width : 1,
      options.maxHeight ? options.maxHeight / bitmap.height : 1,
    )
    const width = Math.max(1, Math.round(bitmap.width * scale))
    const height = Math.max(1, Math.round(bitmap.height * scale))
    const canvas = document.createElement('canvas')
    canvas.width = width
    canvas.height = height
    const ctx = canvas.getContext('2d')
    if (!ctx) throw new Error('Your browser could not create an image canvas.')
    if (options.format === 'image/jpeg') {
      ctx.fillStyle = '#ffffff'
      ctx.fillRect(0, 0, width, height)
    }
    ctx.drawImage(bitmap, 0, 0, width, height)

    if (options.format === 'image/png') {
      const blob = await canvasToBlob(canvas, options.format, 1)
      return { blob, width, height, qualityUsed: 1, reachedTarget: options.targetKB ? blob.size <= options.targetKB * 1024 : true }
    }

    const targetBytes = options.targetKB ? options.targetKB * 1024 : undefined
    if (!targetBytes) {
      const blob = await canvasToBlob(canvas, options.format, options.quality)
      return { blob, width, height, qualityUsed: options.quality, reachedTarget: true }
    }

    // Binary search for the highest quality that meets the requested byte limit.
    let low = 0.05
    let high = 0.95
    let best: Blob | null = null
    let bestQuality = low
    for (let i = 0; i < 9; i++) {
      const q = (low + high) / 2
      const candidate = await canvasToBlob(canvas, options.format, q)
      if (candidate.size <= targetBytes) {
        best = candidate
        bestQuality = q
        low = q
      } else {
        high = q
      }
    }
    if (!best) {
      const smallest = await canvasToBlob(canvas, options.format, 0.05)
      return { blob: smallest, width, height, qualityUsed: 0.05, reachedTarget: smallest.size <= targetBytes }
    }
    return { blob: best, width, height, qualityUsed: bestQuality, reachedTarget: true }
  } finally {
    bitmap.close()
  }
}

export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`
  return `${(bytes / (1024 * 1024)).toFixed(2)} MB`
}

export function safeOutputName(name: string, format: OutputFormat): string {
  const base = name.replace(/\.[^.]+$/, '').replace(/[^\w-]+/g, '-').replace(/^-+|-+$/g, '') || 'image'
  const ext = format === 'image/jpeg' ? 'jpg' : format === 'image/png' ? 'png' : 'webp'
  return `${base}-compressed.${ext}`
}